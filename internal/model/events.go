package model

import "time"

// RawEvent represents the raw, foundational data structure ingested from the queue by the Collector.
type RawEvent struct {
	ID                string            `json:"id"`
	Body              string            `json:"body"`
	Provider          string            `json:"provider"` // e.g., "SQS", "RabbitMQ"
	Attributes        map[string]string `json:"attributes"`
	FirstSeen         time.Time         `json:"first_seen"`
	LastSeen          time.Time         `json:"last_seen"`
	ReceiveCount      int               `json:"receive_count"`
	OriginalQueueName string            `json:"original_queue_name"`
}

// FailureRecord extends the raw event with deterministic classifications generated by the Normalizer and Classifier.
type FailureRecord struct {
	RawEventID      string `json:"raw_event_id"`
	ErrorSignature  string `json:"error_signature"` // The SHA-256 hash of the normalized error
	NormalizedError string `json:"normalized_error"`
	PayloadShape    string `json:"payload_shape"`  // JSON key structure fingerprint (e.g., "error,payload.action,payload.id")
	FailureClass    string `json:"failure_class"`  // Group identifier from the Classifier
	Classification  string `json:"classification"` // E.g., "Poison Message", "Downstream Dependency"
	Severity        string `json:"severity"`       // "critical", "warning", "info"
	RetryVerdict    string `json:"retry_verdict"`  // "safe_to_retry", "do_not_retry", "retry_with_backoff", "needs_investigation"
}

// RunSummary represents an aggregated overview of a specific analysis run.
type RunSummary struct {
	Name         string    `json:"name"`
	MessageCount int       `json:"message_count"`
	FirstSeen    time.Time `json:"first_seen"`
	LastSeen     time.Time `json:"last_seen"`
}
